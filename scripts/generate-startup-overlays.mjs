#!/usr/bin/env node
/**
 * Renders each startup polygon as a full-canvas transparent PNG overlay
 * (412x915 matching splash-polygons-bg.png 1:1) so the app can light polygons
 * with native-driver Animated.Image opacity and instant bitmap decoding.
 *
 * Run: node scripts/generate-startup-overlays.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { Resvg } from '@resvg/resvg-js';

const require = createRequire(import.meta.url);
const { V, default: POLYGONS } = require('../src/components/startupPolygons.js');

const WIDTH = 412;
const HEIGHT = 915;
const SCALE = 1;
const OUT_DIR = path.join('assets', 'images', 'startup-overlays');

const GRADS = `
  <defs>
    <linearGradient id="leftGrad" x1="0%" y1="15%" x2="100%" y2="85%">
      <stop offset="0%" stop-color="#FFFFFF" stop-opacity="0.44"/>
      <stop offset="28%" stop-color="#FFFFFF" stop-opacity="0.26"/>
      <stop offset="68%" stop-color="#F8FAFC" stop-opacity="0.11"/>
      <stop offset="100%" stop-color="#FFFFFF" stop-opacity="0.22"/>
    </linearGradient>
    <linearGradient id="rightGrad" x1="100%" y1="15%" x2="0%" y2="85%">
      <stop offset="0%" stop-color="#FFFFFF" stop-opacity="0.44"/>
      <stop offset="28%" stop-color="#FFFFFF" stop-opacity="0.26"/>
      <stop offset="68%" stop-color="#F8FAFC" stop-opacity="0.11"/>
      <stop offset="100%" stop-color="#FFFFFF" stop-opacity="0.22"/>
    </linearGradient>
  </defs>`;

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });

const requires = [];
for (const poly of POLYGONS) {
  const grad = poly.side === 'left' ? 'url(#leftGrad)' : 'url(#rightGrad)';
  const points = poly.pts.map((k) => V[k].join(',')).join(' ');
  const svg =
    `<svg width="${WIDTH}" height="${HEIGHT}" viewBox="0 0 ${WIDTH} ${HEIGHT}" ` +
    `xmlns="http://www.w3.org/2000/svg">${GRADS}` +
    `<polygon points="${points}" fill="${grad}" stroke="#FFFFFF" stroke-opacity="0.30" stroke-width="3.6" stroke-linejoin="round"/>` +
    `<polygon points="${points}" fill="none" stroke="#FFFFFF" stroke-opacity="0.82" stroke-width="1.2" stroke-linejoin="round"/>` +
    `</svg>`;
  const png = new Resvg(svg, { fitTo: { mode: 'width', value: WIDTH * SCALE } })
    .render()
    .asPng();
  const name = `lit-${poly.id}.png`;
  fs.writeFileSync(path.join(OUT_DIR, name), png);
  requires.push(`  require('../../assets/images/${path.posix.join('startup-overlays', name)}'),`);
  console.log(`${name}: ${png.length} bytes`);
}

const indexSrc = `// Generated by scripts/generate-startup-overlays.mjs - do not edit by hand.\n// Index-aligned with STARTUP_POLYGONS: one full-canvas lit overlay per polygon.\nexport default [\n${requires.join('\n')}\n];\n`;
fs.writeFileSync(path.join('src', 'components', 'startupOverlays.js'), indexSrc);
console.log(`wrote src/components/startupOverlays.js (${POLYGONS.length} overlays)`);
